import json
import importlib
import os
import sys
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from tools.stageTwoTools.stage_2_tools import stage2_tools
from tools.stageTwoTools.stage_2_dispatcher import get_root_threat_scenarios, add_attack_tree_node, save_attack_feasibility, get_item_definition

try:
    OpenAI = importlib.import_module("openai").OpenAI
except ModuleNotFoundError as exc:
    if exc.name != "openai":
        raise
    raise RuntimeError(
        "The 'openai' package is required. Install it with: python -m pip install openai"
    ) from exc

client = OpenAI(
    api_key=os.getenv("OPENAI_API_KEY", "ollama"),
    base_url=os.getenv("OPENAI_BASE_URL", "http://localhost:11434/v1")
)

def execute_tool(name, args):
    if name == "get_root_threat_scenarios":
        return get_root_threat_scenarios()
    elif name == "get_item_definition":
        return get_item_definition()
    elif name == "add_attack_tree_node":
        return add_attack_tree_node(**args)
    elif name == "save_attack_feasibility":
        return save_attack_feasibility(**args)
    else:
        return {"error": f"Unknown tool: {name}"}

def run_stage2_agent():
    system_prompt = """
You are the Stage 2 TARA Agent specializing in ISO/SAE 21434 Attack Path Analysis and Attack Feasibility Rating (Clauses 15.6 & 15.7).
Your task is to build grounded, realistic multi-tier attack trees for every root threat scenario generated by Stage 1:

1. First, call 'get_item_definition' to study the precise system architecture, component boundaries, hardware types, interfaces, and security configurations. You must NEVER assume or invent interfaces that do not exist in this definition.
2. Next, call 'get_root_threat_scenarios' to fetch all root threats stored in 'tara_scenarios.db'.
3. For each root threat scenario, construct a structured attack tree by adding hierarchical child nodes ('AND_GATE', 'OR_GATE', and 'LEAF_EXPLOIT') using the 'add_attack_tree_node' tool:
   - Connect each node directly to its parent (starting from the Stage 1 root node ID).
   - Ensure every leaf exploit explicitly targets a real interface, protocol, or misconfiguration cited in the item definition or the root threat's root cause. Do not hallucinate capabilities.
4. For each constructed attack path or leaf node, determine and save its attack feasibility rating ('High', 'Medium', 'Low', 'Very low') using the 'save_attack_feasibility' tool, evaluating parameters such as attack vector, elapsed time, expertise, and equipment per ISO 21434 Annex G.
"""

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": "Load the item definition and root threat scenarios, cross-reference the physical/logical boundaries, build realistic attack trees with logic gates and leaf exploits, and assign attack feasibility ratings."}
    ]

    print("Stage 2 Agent: Grounded Attack Tree Construction & Feasibility Rating started...\n")
    
    turn_count = 0
    max_turns = 30 

    while turn_count < max_turns:
        turn_count += 1
    
       
        if turn_count == 1:
            current_tool_choice = {"type": "function", "function": {"name": "get_item_definition"}}
        elif turn_count == 2:
            current_tool_choice = {"type": "function", "function": {"name": "get_root_threat_scenarios"}}
        else:
            current_tool_choice = "auto"

        response = client.chat.completions.create(
            model="qwen3.5-65k",
            messages=messages,
            tools=stage2_tools,
            tool_choice=current_tool_choice,
        )
        
        msg = response.choices[0].message
        messages.append(msg)
        
        if msg.tool_calls:
            for tool_call in msg.tool_calls:
                fn_name = tool_call.function.name
                try:
                    fn_args = json.loads(tool_call.function.arguments)
                except json.JSONDecodeError:
                    fn_args = {}

                print(f"[Tool Call]: {fn_name} with args keys: {list(fn_args.keys())}")
                
                result = execute_tool(fn_name, fn_args)
                print(f"[Tool Result]: {result}\n")
                
                messages.append({
                    "role": "tool",
                    "tool_call_id": tool_call.id,
                    "content": json.dumps(result)
                })
        else:
            print("\nStage 2 Agent Completed Execution!")
            print(msg.content)
            break

if __name__ == "__main__":
    run_stage2_agent()